import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, "fonts", "Montserrat-Variable.ttf")
OUT = os.path.join(HERE, "..", "src", "fonts")

DIGITS = "0123456789-"
TEXT = " %-./:°" + "0123456789" + "ABCDEFGHIJKLMNOPQRSTUVWXYZ"

FONTS = [
    ("font_big", 600, 172, DIGITS, 0),
    ("font_mid", 600, 92, DIGITS, 0),
    ("font_unit", 500, 44, "°%CF", 0),
    ("font_label", 600, 26, TEXT, 3),
    ("font_small", 500, 20, TEXT, 2),
]


def build(name, weight, size, chars, tracking):
    font = ImageFont.truetype(TTF, size)
    font.set_variation_by_axes([weight])
    nibbles = []
    glyphs = []
    for ch in chars:
        advance = round(font.getlength(ch)) + tracking
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        w, h = max(right - left, 0), max(bottom - top, 0)
        offset = len(nibbles)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
            nibbles.extend((p * 15 + 127) // 255 for p in img.tobytes())
        glyphs.append((ord(ch), w, h, left, top, advance, offset))
    if len(nibbles) % 2:
        nibbles.append(0)
    data = bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2))
    ascent, descent = font.getmetrics()
    cap = -font.getbbox("0", anchor="ls")[1]

    lines = [
        "#pragma once",
        "#include \"font.h\"",
        "",
        f"// Montserrat (SIL OFL 1.1), weight {weight}, {size}px. Generated by tools/gen_fonts.py",
        f"static const uint8_t {name}_bitmap[] = {{",
    ]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const Glyph {name}_glyphs[] = {{")
    for code, w, h, xo, yo, adv, off in glyphs:
        lines.append(f"    {{0x{code:04x}, {w}, {h}, {xo}, {yo}, {adv}, {off}}},")
    lines.append("};")
    lines.append(
        f"static const Font {name} = {{{name}_bitmap, {name}_glyphs, {len(glyphs)}, {ascent}, {cap}}};"
    )
    with open(os.path.join(OUT, f"{name}.h"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{name}: {len(glyphs)} glyphs, {len(data)} bytes")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for spec in FONTS:
        build(*spec)
